class ifelse
{
    public static void main(String args[])
    {
        int marks=70;
        if(marks>=80)
        {
            System.out.println("O");
        }
        else
        {
            if(marks>=80 & marks<=90)
        {
            System.out.println("A+");
        }
        else {
            if(marks>=70 & marks<=80)
        {
            System.out.println("A");
        }
        }
        }
        

        
    }
}